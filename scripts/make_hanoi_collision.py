"""Generate simulation wrappers for the Tower of Hanoi disks (plain python3, no USD libraries needed).

    python3 scripts/make_hanoi_collision.py

Each ``assets/Tower_of_Hanoi/sim/disk_*.usda`` references the original disk (visual mesh, mass,
visual material untouched) and replaces its ``convexDecomposition`` collider with two concentric
rings of box segments. The inner 1.5 mm lining uses low friction for sliding along the peg;
the outer ring uses high friction for gripping. Separate shapes are needed because a single
PhysX convex collider cannot assign different friction coefficients to its inside/outside faces.
The 12 mm centre hole stays open instead of being bridged by convex decomposition.
"""

from __future__ import annotations

import math
import os

HANOI_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "assets", "Tower_of_Hanoi")
DISKS = {"disk_28mm_red": 0.014, "disk_36mm_green": 0.018, "disk_44mm_blue": 0.022}  # outer radius [m]
INNER_RADIUS = 0.006
LINER_RADIUS = 0.0075
THICKNESS = 0.008
SEGMENTS = 16


def ring_segments(name: str, band: str, inner: float, outer: float) -> str:
    radial = outer - inner
    mid = (inner + outer) / 2
    tangential = 2 * outer * math.tan(math.pi / SEGMENTS)
    segments = []
    for i in range(SEGMENTS):
        angle = 360.0 * i / SEGMENTS
        a = math.radians(angle)
        segments.append(f"""
            def Cube "{band}_{i:02d}" (
                prepend apiSchemas = ["PhysicsCollisionAPI", "PhysxCollisionAPI", "MaterialBindingAPI"]
            )
            {{
                double size = 1
                uniform token purpose = "guide"
                float physxCollision:contactOffset = 0.0005
                float physxCollision:restOffset = 0
                rel material:binding:physics = </{name}/Looks/physics_{band}> (
                    bindMaterialAs = "strongerThanDescendants"
                )
                double3 xformOp:translate = ({mid * math.cos(a):.6f}, {mid * math.sin(a):.6f}, {THICKNESS / 2:.6f})
                float xformOp:rotateZ = {angle:.4f}
                float3 xformOp:scale = ({radial:.6f}, {tangential:.6f}, {THICKNESS:.6f})
                uniform token[] xformOpOrder = ["xformOp:translate", "xformOp:rotateZ", "xformOp:scale"]
            }}""")
    return "".join(segments)


def disk_usda(name: str, outer: float) -> str:
    segments = ring_segments(name, "bore", INNER_RADIUS, LINER_RADIUS)
    segments += ring_segments(name, "rim", LINER_RADIUS, outer)
    return f"""#usda 1.0
(
    defaultPrim = "{name}"
    kilogramsPerUnit = 1
    metersPerUnit = 1
    upAxis = "Z"
)

# Generated by scripts/make_hanoi_collision.py -- do not edit by hand.
def Xform "{name}" (
    prepend references = @../{name}.usda@
)
{{
    over "geometry"
    {{
        bool physics:collisionEnabled = 0
    }}

    over "Looks"
    {{
        def Material "physics_rim" (
            prepend apiSchemas = ["PhysicsMaterialAPI", "PhysxMaterialAPI"]
        )
        {{
            float physics:staticFriction = 1.5
            float physics:dynamicFriction = 1.2
            float physics:restitution = 0
            token physxMaterial:frictionCombineMode = "max"
        }}
        def Material "physics_bore" (
            prepend apiSchemas = ["PhysicsMaterialAPI", "PhysxMaterialAPI"]
        )
        {{
            float physics:staticFriction = 0.02
            float physics:dynamicFriction = 0.01
            float physics:restitution = 0
            token physxMaterial:frictionCombineMode = "min"
        }}
    }}

    def Xform "collision"
    {{{segments}
    }}
}}
"""


if __name__ == "__main__":
    out_dir = os.path.join(HANOI_DIR, "sim")
    os.makedirs(out_dir, exist_ok=True)
    for name, outer in DISKS.items():
        path = os.path.join(out_dir, f"{name}.usda")
        with open(path, "w") as file:
            file.write(disk_usda(name, outer))
        print("wrote", path)
